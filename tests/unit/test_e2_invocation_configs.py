def test_emits_exactly_three_configs_in_order(tmp_path):
    source = _write_source(tmp_path)
    written = emit_invocation_configs(source, tmp_path / "invocations")
    assert [p.name for p in written] == [
        "config_e2_classification.yaml",
        "config_e2_timing.yaml",
        "config_e2_memory.yaml",
    ]
    assert all(p.exists() for p in written)


def test_variant_internals_match_d15_and_d16(tmp_path):
    source = _write_source(tmp_path)
    written = emit_invocation_configs(source, tmp_path / "invocations")
    internals = [yaml.safe_load(p.read_text())["internals"] for p in written]
    classification, timing, memory = internals

    # D-16: the ~11 MB h_q sidecar rides the classification run only.
    assert classification["log_all_observation_depths"] is True
    assert classification["benchmark_memory"] is False
    # D-15: the timing run carries neither perturbation.
    assert timing["log_all_observation_depths"] is False
    assert timing["benchmark_memory"] is False
    # D-15: memory instrumentation is its own run.
    assert memory["log_all_observation_depths"] is False
    assert memory["benchmark_memory"] is True


def test_no_variant_sets_both_internals_flags_true(tmp_path):
    source = _write_source(tmp_path)
    written = emit_invocation_configs(source, tmp_path / "invocations")
    for path in written:
        internals = yaml.safe_load(path.read_text())["internals"]
        assert not (
            internals["benchmark_memory"] and internals["log_all_observation_depths"]
        ), f"{path.name} sets both perturbing internals keys true"
    # And the same is true of the declarative table itself.
    for spec in E2_INVOCATION_VARIANTS:
        overrides = spec["internals"]
        assert not (
            overrides["benchmark_memory"] and overrides["log_all_observation_depths"]
        )


def test_variants_have_distinct_output_dirs(tmp_path):
    source = _write_source(tmp_path)
    written = emit_invocation_configs(source, tmp_path / "invocations")
    output_dirs = [
        yaml.safe_load(p.read_text())["paths"]["output_dir"] for p in written
    ]
    assert len(set(output_dirs)) == 3
    assert all(d != "/original/output_dir" for d in output_dirs)


def test_refuses_to_write_into_the_source_config_directory(tmp_path):
    source = _write_source(tmp_path)
    with pytest.raises(ValueError, match="inside the source config's own directory"):
        emit_invocation_configs(source, source.parent)


def test_refuses_to_write_under_the_source_config_directory(tmp_path):
    source = _write_source(tmp_path)
    with pytest.raises(ValueError, match="inside the source config's own directory"):
        emit_invocation_configs(source, source.parent / "nested" / "deeper")


def test_scope_sidecar_records_sha256_and_settings(tmp_path):
    source = _write_source(tmp_path)
    target = tmp_path / "invocations"
    emit_invocation_configs(source, target)
    record = json.loads((target / "e2_invocation_scope.json").read_text())

    expected_sha = hashlib.sha256(source.read_bytes()).hexdigest()
    assert record["source_config_sha256"] == expected_sha
    assert record["n"] == 3
    names = [v["name"] for v in record["variants"]]
    assert names == ["classification", "timing", "memory"]
    for variant in record["variants"]:
        assert set(variant["internals"]) == {
            "benchmark_memory",
            "log_all_observation_depths",
        }
        assert variant["output_dir"]
        assert variant["filename"].startswith("config_e2_")
    assert len({v["output_dir"] for v in record["variants"]}) == 3


def test_source_config_is_never_modified(tmp_path):
    source = _write_source(tmp_path)
    before = source.read_bytes()
    emit_invocation_configs(source, tmp_path / "invocations")
    assert source.read_bytes() == before


