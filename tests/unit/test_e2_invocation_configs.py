def _passed(name: str) -> ComparisonReport:
    return ComparisonReport(
        passed=True,
        worst_cell=None,
        worst_rtol=0.0,
        n_mismatched_cells=0,
        message=f"{name} matched within tolerance",
    )


def _failed(name: str) -> ComparisonReport:
    return ComparisonReport(
        passed=False,
        worst_cell="cam0/x_m",
        worst_rtol=1e-3,
        n_mismatched_cells=4,
        message=f"{name} MISMATCH at 4 cells",
    )


def test_all_baselines_present_and_matching_exits_zero(tmp_path, capsys):
    reports = [
        (name, tmp_path / name, _passed(name)) for name in ("a.csv", "b.csv", "c.csv")
    ]
    assert _fold_check_reports(reports) == 0
    out = capsys.readouterr().out
    assert "matched within tolerance" in out
    assert "N/A" not in out


def test_missing_baseline_is_na_and_does_not_fail(tmp_path, capsys):
    reports = [
        ("camera_parameters.csv", tmp_path / "camera_parameters.csv", _passed("cp")),
        ("reprojection_residuals.csv", tmp_path / "reprojection_residuals.csv", None),
        ("reconstruction_errors.csv", tmp_path / "reconstruction_errors.csv", None),
    ]
    assert _fold_check_reports(reports) == 0
    out = capsys.readouterr().out
    assert out.count("N/A") == 2
    assert "reprojection_residuals.csv" in out
    assert "DATA-01b" in out


def test_present_and_differing_baseline_still_fails(tmp_path, capsys):
    reports = [
        ("camera_parameters.csv", tmp_path / "camera_parameters.csv", _failed("cp")),
        ("reprojection_residuals.csv", tmp_path / "reprojection_residuals.csv", None),
        ("reconstruction_errors.csv", tmp_path / "reconstruction_errors.csv", None),
    ]
    assert _fold_check_reports(reports) == 1
    assert "MISMATCH" in capsys.readouterr().out


def test_all_absent_is_vacuous_and_never_reads_as_a_pass(tmp_path, capsys):
    reports = [
        (name, tmp_path / name, None)
        for name in (
            "camera_parameters.csv",
            "reprojection_residuals.csv",
            "reconstruction_errors.csv",
        )
    ]
    assert _fold_check_reports(reports) != 0
    out = capsys.readouterr().out
