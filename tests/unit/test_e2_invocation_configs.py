"""Unit tests for E2's D-15/D-16 invocation-config generator and its honest
`--check` verdict (Phase 26 plan 26-06).

Two surfaces are covered:

1. `build_internals_variant_config` / `emit_invocation_configs` -- the pure
   text-to-text `internals.*` override transform and the three-variant emitter
   that makes E2's classification / timing / memory invocations distinct
   (D-15: `internals.benchmark_memory` costs 2.7-5.5% wall clock, so one run
   cannot honestly produce both the timing and the memory number; D-16:
   `internals.log_all_observation_depths` writes an ~11 MB per-stage sidecar
   and therefore rides the classification run only).
2. `_fold_check_reports` -- E2's `--check` verdict folding, where a baseline
   gitignored by DATA-01b policy is an N/A rather than a crash (ruling A4),
   but an all-N/A check is never a pass.

Every test uses a small inline fixture config -- never the real Desktop
production config -- so the suite has no external dependency and never touches
`C:/Users/tucke/Desktop/Aqua/AquaCal/release_calibration/`. **No test here
invokes `run_calibration` or performs a calibration**: one E2 run is 48-87
minutes and needs a 4.35 GB frameset.
"""

